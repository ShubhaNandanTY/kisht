export const DICTS: Record<Lang, Dict> = { en, hi };
export type MsgKey = keyof typeof en;

export function translate(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const d = DICTS[lang] as Record<string, string>;
  let s = d[key] ?? (DICTS.en as Record<string, string>)[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    const val = typeof v === "number" && k === "amount" ? formatMoney(v) : String(v);
    s = s.replaceAll(`{${k}}`, val);
  }
  return s;
}

export function formatMoney(n: number): string {
  return new Intl.NumberFormat("en-IN", { maximumFractionDigits: 0 }).format(n);
}

/** ₹6.4 L / ₹31,000 — lakhs are how Indian business people talk about loan sizes. */
export function formatMoneyShort(n: number): string {
  if (n >= 10_000_000) return `${(n / 10_000_000).toFixed(2).replace(/\.?0+$/, "")} Cr`;
  if (n >= 100_000) return `${(n / 100_000).toFixed(1).replace(/\.0$/, "")} L`;
  return formatMoney(n);
}
